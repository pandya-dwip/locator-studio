// The <Name>.spec file: executable Playwright tests that use the generated
// page class and test data. Every test asserts something real; cases that
// still need configuration are skipped with the reason, never passed.
import type { FormSpec } from './forms'
import { camelCase, words } from './naming'
import type { ModuleFormat } from './pom-generator'
import { PLACEHOLDER, testDataNames } from './test-data'
import type { OutputLanguage } from '../../shared/types'
import { jsString } from '../../core/locator-engine/utils/escaping'

export function renderSpec(o: {
  baseName: string
  className: string
  pageModule: string
  dataModule: string
  dataFile: string
  title: string
  forms: FormSpec[]
  hasExpectLoaded: boolean
  language: OutputLanguage
  moduleFormat: ModuleFormat
}): string {
  const ts = o.language === 'typescript'
  const esm = ts || o.moduleFormat === 'esm'
  const names = testDataNames(o.baseName)
  const instance = camelCase(words(o.className))
  const usesTitle = !!o.title
  const dataImports = [
    ...(usesTitle ? [names.pageInfo] : []),
    ...o.forms.flatMap((f) => [names.data(f), ...(ts ? [`type ${names.caseType(f)}`] : [])]),
  ]
  const needsUrlHelper = o.forms.length > 0

  const lines: string[] = [
    `// Playwright tests for ${o.className}. Generated by Locator Studio.`,
    `// Test cases live in ${o.dataFile}. Cases with "${PLACEHOLDER}" placeholders or without an expected result are skipped, with the reason.`,
  ]
  if (esm) {
    lines.push(`import { test, expect } from '@playwright/test';`, `import { ${o.className} } from '${o.pageModule}';`)
    if (dataImports.length) lines.push(`import { ${dataImports.join(', ')} } from '${o.dataModule}';`)
  } else {
    lines.push(`const { test, expect } = require('@playwright/test');`, `const { ${o.className} } = require('${o.pageModule}');`)
    if (dataImports.length) lines.push(`const { ${dataImports.join(', ')} } = require('${o.dataModule}');`)
  }

  lines.push('', `test.describe(${jsString(o.baseName)}, () => {`)
  // Smoke test: the page opens and its key elements are there.
  lines.push(
    "  test('page loads with its key elements', async ({ page }) => {",
    `    const ${instance} = new ${o.className}(page);`,
    `    await ${instance}.goto();`,
  )
  if (usesTitle) lines.push(`    await expect(page).toHaveTitle(${names.pageInfo}.title);`)
  if (o.hasExpectLoaded) lines.push(`    await ${instance}.expectLoaded();`)
  if (!usesTitle && !o.hasExpectLoaded) lines.push(`    await expect(page).toHaveURL(${o.className}.url);`)
  lines.push('  });')

  for (const f of o.forms) {
    const caseType = names.caseType(f)
    const check = `missing${caseType.replace(/TestCase$/, '')}Configuration`
    const args = f.params.map((p) => `data.${p.name}`).join(', ')
    lines.push(
      '',
      `  test.describe(${jsString(f.method)}, () => {`,
      `    for (const data of ${names.data(f)}) {`,
      '      test(data.name, async ({ page }) => {',
      `        const missing = ${check}(data);`,
      "        test.skip(missing !== null, missing ?? '');",
      `        const ${instance} = new ${o.className}(page);`,
      `        await ${instance}.goto();`,
      `        await ${instance}.${f.method}(${args});`,
      "        if (data.expected === 'success') {",
      '          if (data.expectedUrl) await expect(page).toHaveURL(urlContaining(data.expectedUrl));',
      '          if (data.expectedText) await expect(page.getByText(data.expectedText).first()).toBeVisible();',
    )
    if (f.message) lines.push(`          await expect(${instance}.${f.message}).toBeHidden();`)
    lines.push('        } else {')
    if (f.message) {
      lines.push(
        `          await expect(${instance}.${f.message}).toBeVisible();`,
        `          if (data.expectedText) await expect(${instance}.${f.message}).toContainText(data.expectedText);`,
      )
    } else {
      lines.push(`          await expect(page.getByText(data.expectedText${ts ? '!' : ''}).first()).toBeVisible();`)
    }
    lines.push('        }', '      });', '    }', '  });')
  }
  lines.push('});')

  for (const f of o.forms) {
    const caseType = names.caseType(f)
    const check = `missing${caseType.replace(/TestCase$/, '')}Configuration`
    lines.push(
      '',
      '/** Why a test case cannot run yet (placeholders or no expected result), or null when it is ready. */',
      ts ? `function ${check}(data: ${caseType}): string | null {` : `function ${check}(data) {`,
      '  const placeholders = Object.entries(data)',
      `    .filter(([, value]) => typeof value === 'string' && value.startsWith(${jsString(PLACEHOLDER)}))`,
      '    .map(([key]) => key);',
      `  if (placeholders.length) return \`Replace the ${PLACEHOLDER} placeholder in \${placeholders.join(', ')} (${o.dataFile})\`;`,
      "  if (data.expected === 'success' && !data.expectedUrl && !data.expectedText) {",
      `    return 'Set expectedUrl or expectedText for this success case (${o.dataFile})';`,
      '  }',
    )
    if (!f.message) {
      lines.push(
        "  if (data.expected === 'failure' && !data.expectedText) {",
        `    return 'Set expectedText (the error shown) for this failure case (${o.dataFile})';`,
        '  }',
      )
    }
    lines.push('  return null;', '}')
  }
  if (needsUrlHelper) {
    lines.push(
      '',
      '/** Matches any URL containing `part`. */',
      ts ? 'function urlContaining(part: string): RegExp {' : 'function urlContaining(part) {',
      "  return new RegExp(part.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&'));",
      '}',
    )
  }
  return `${lines.join('\n')}\n`
}
